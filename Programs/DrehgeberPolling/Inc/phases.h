#include <stdint.h>
#ifndef phases
#define phases
/*
 ****************************************************************************************
 *  @brief      Outputs degrees and velocity on display, reads buttons for the
 *next Phase
 * *
 *  @return     Next Phase
 ****************************************************************************************/
enum NextPhase phase_a(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Outputs degrees and velocity on display, reads buttons for the
 *next Phase
 * *
 *  @return     Next Phase
 ****************************************************************************************/
enum NextPhase phase_b(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Outputs degrees and velocity on display, reads buttons for the
 *next Phase
 * *
 *  @return     Next Phase
 ****************************************************************************************/
enum NextPhase phase_c(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Outputs degrees and velocity on display, reads buttons for the
 *next Phase
 * *
 *  @return     Next Phase
 ****************************************************************************************/
enum NextPhase phase_d(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Sets direction to forward
 * *
 *  @return     Phase B
 ****************************************************************************************/
enum NextPhase a_to_b(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to backward
 * *
 *  @return     Phase D
 ****************************************************************************************/
enum NextPhase a_to_d(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to forward
 * *
 *  @return     Phase C
 ****************************************************************************************/
enum NextPhase b_to_c(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to backward
 * *
 *  @return     Phase A
 ****************************************************************************************/
enum NextPhase b_to_a(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to backward
 * *
 *  @return     Phase B
 ****************************************************************************************/
enum NextPhase c_to_b(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to forward
 * *
 *  @return     Phase D
 ****************************************************************************************/
enum NextPhase c_to_d(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to forward
 * *
 *  @return     Phase A
 ****************************************************************************************/
enum NextPhase d_to_a(void);
/*
 ****************************************************************************************
 *  @brief      Sets direction to backward
 * *
 *  @return     Phase C
 ****************************************************************************************/
enum NextPhase d_to_c(void);
/*
 ****************************************************************************************
 *  @brief      Waits for Button S6, also sets Error LED and clears the other 2
 * *
 *  @return     Phase INIT
 ****************************************************************************************/
enum NextPhase error(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Sets degree, velocity to 0
 * *
 *  @return     NextPhase
 ****************************************************************************************/
enum NextPhase init(uint32_t);
/*
 ****************************************************************************************
 *  @brief      Enum Defition for NextPhase
 * *
 ****************************************************************************************/
enum NextPhase {
   INIT,
   A,
   B,
   C,
   D,
   ERRORPHASE,
};
/*
 ****************************************************************************************
 *  @brief      Executes the next phase from a function poiter
 * *
 *  @return     NextPhase
 ****************************************************************************************/
typedef enum NextPhase (*phase_fn)(uint32_t buttons);
extern phase_fn phase_ops[];

#endif